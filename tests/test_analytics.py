"""
Tests for SaaS Analytics Modules (Customer, Revenue, LTV, Cohort)
"""

import os
import sys
import pytest
import pandas as pd
import numpy as np

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_ROOT)

from src.customer_analysis import (
    analyze_customer_overview,
    analyze_customer_segments,
    analyze_contract_impact
)
from src.revenue_analysis import (
    calculate_mrr,
    revenue_by_subscription,
    revenue_at_risk
)
from src.ltv_analysis import (
    calculate_overall_ltv,
    ltv_quartile_analysis
)
from src.cohort_analysis import (
    build_cohort_summary,
    analyze_early_churn
)


@pytest.fixture(scope="module")
def processed_data():
    """Load cleaned dataset generated by pipeline."""
    cleaned_path = os.path.join(PROJECT_ROOT, "data", "processed", "saas_customer_cleaned.csv")
    if not os.path.exists(cleaned_path):
        pytest.skip("Processed dataset not available yet")
    return pd.read_csv(cleaned_path)


def test_customer_overview_calculation(processed_data):
    """Verify customer overview counts and rates."""
    overview = analyze_customer_overview(processed_data)
    
    assert overview['total_customers'] == len(processed_data)
    assert overview['active_customers'] + overview['churned_customers'] == overview['total_customers']
    assert 0 <= overview['churn_rate_pct'] <= 100
    assert 0 <= overview['retention_rate_pct'] <= 100
    assert round(overview['churn_rate_pct'] + overview['retention_rate_pct'], 1) == 100.0


def test_customer_segments_aggregation(processed_data):
    """Verify segment breakdown aggregates properly."""
    segments = analyze_customer_segments(processed_data)
    
    assert segments['CustomerCount'].sum() == len(processed_data)
    assert round(segments['RevenueShare'].sum(), 0) == 100.0


def test_calculate_mrr_and_arr(processed_data):
    """Verify MRR and ARR logic."""
    rev_kpis = calculate_mrr(processed_data)
    
    active_mrr = processed_data[processed_data['Churn'] == 'No']['MonthlyCharges'].sum()
    assert round(rev_kpis['mrr'], 1) == round(active_mrr, 1)
    assert round(rev_kpis['arr'], 1) == round(active_mrr * 12, 1)
    assert rev_kpis['arpu'] > 0


def test_ltv_overall_and_quartiles(processed_data):
    """Verify overall LTV and quartile distributions."""
    overall = calculate_overall_ltv(processed_data)
    assert overall['avg_ltv'] > 0
    assert overall['total_lifetime_revenue'] == round(processed_data['TotalCharges'].sum(), 2)

    quartiles = ltv_quartile_analysis(processed_data)
    avg_ltvs = quartiles['AvgLTV'].tolist()
    assert len(avg_ltvs) == 4
    for i in range(len(avg_ltvs) - 1):
        assert avg_ltvs[i] <= avg_ltvs[i + 1]


def test_cohort_summary_and_early_churn(processed_data):
    """Verify cohort aggregations and early churn metrics."""
    cohorts = build_cohort_summary(processed_data)
    assert len(cohorts) > 0
    assert (cohorts['RetentionRate'] >= 0).all()
    assert (cohorts['RetentionRate'] <= 100).all()
    assert cohorts['CohortSize'].sum() == len(processed_data)

    early_churn = analyze_early_churn(processed_data)
    assert len(early_churn) > 0
    assert 'EarlyChurnRate' in early_churn.columns

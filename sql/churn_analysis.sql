-- ============================================================================
-- CHURN ANALYSIS QUERIES
-- ============================================================================
-- Database: SQLite (saas_analytics.db)
-- Table: customers (loaded from cleaned dataset)
--
-- Formulas & Assumptions:
--   Churn Rate = Churned Customers / Total Customers × 100
--   Revenue Lost = SUM(MonthlyCharges) of churned customers (monthly impact)
--   All churn labels are historical (Churn = 'Yes' or 'No'), not predicted.
-- ============================================================================

-- C1. Overall churn rate
SELECT 
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    SUM(CASE WHEN Churn = 'No' THEN 1 ELSE 0 END) AS ActiveCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(SUM(CASE WHEN Churn = 'No' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS RetentionRatePct
FROM customers;

-- C2. Churn rate by contract type
SELECT 
    ContractDuration,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(Tenure), 1) AS AvgTenure,
    ROUND(AVG(MonthlyCharges), 2) AS AvgMonthlyCharges
FROM customers
GROUP BY ContractDuration
ORDER BY ChurnRatePct DESC;

-- C3. Churn by customer tenure
SELECT 
    TenureGroup,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(MonthlyCharges), 2) AS AvgMonthlyCharges
FROM customers
GROUP BY TenureGroup
ORDER BY 
    CASE TenureGroup
        WHEN '0-6 months' THEN 1
        WHEN '7-12 months' THEN 2
        WHEN '13-24 months' THEN 3
        WHEN '25-36 months' THEN 4
        ELSE 5
    END;

-- C4. Churn by payment method
SELECT 
    PaymentMethod,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(MonthlyCharges), 2) AS AvgMonthlyCharges,
    ROUND(AVG(Tenure), 1) AS AvgTenure
FROM customers
GROUP BY PaymentMethod
ORDER BY ChurnRatePct DESC;

-- C5. Churn by monthly charges (charge bands)
SELECT 
    ChargeBand,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(SupportTickets), 1) AS AvgSupportTickets
FROM customers
GROUP BY ChargeBand
ORDER BY 
    CASE ChargeBand
        WHEN '$0-30' THEN 1
        WHEN '$31-60' THEN 2
        WHEN '$61-100' THEN 3
        WHEN '$101-150' THEN 4
        WHEN '$150+' THEN 5
    END;

-- C6. Churn by support ticket volume
SELECT 
    TicketCategory,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(MonthlyCharges), 2) AS AvgMonthlyCharges,
    ROUND(AVG(Tenure), 1) AS AvgTenure
FROM customers
GROUP BY TicketCategory
ORDER BY 
    CASE TicketCategory
        WHEN 'None' THEN 1
        WHEN 'Low (1-2)' THEN 2
        WHEN 'Medium (3-5)' THEN 3
        WHEN 'High (5+)' THEN 4
    END;

-- C7. Revenue lost due to churn (monthly and annualized)
-- This represents the monthly revenue that was being generated by customers
-- who subsequently churned. It is the MRR impact of churn.
SELECT 
    ROUND(SUM(MonthlyCharges), 2) AS Monthly_Revenue_Lost,
    ROUND(SUM(MonthlyCharges) * 12, 2) AS Annualized_Revenue_Lost,
    COUNT(*) AS Churned_Customers,
    ROUND(AVG(MonthlyCharges), 2) AS Avg_Monthly_Revenue_Per_Churned,
    ROUND(SUM(TotalCharges), 2) AS Total_Revenue_Before_Churn
FROM customers
WHERE Churn = 'Yes';

-- C8. Churn by customer segment
SELECT 
    CustomerSegment,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS MRR_Lost,
    ROUND(AVG(CASE WHEN Churn = 'Yes' THEN Tenure ELSE NULL END), 1) AS AvgChurnedTenure,
    ROUND(AVG(CASE WHEN Churn = 'Yes' THEN SupportTickets ELSE NULL END), 1) AS AvgChurnedTickets
FROM customers
GROUP BY CustomerSegment
ORDER BY ChurnRatePct DESC;

-- C9. Churn by subscription + contract combination
-- Identifies the most vulnerable customer profiles.
SELECT 
    SubscriptionType,
    ContractDuration,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN MonthlyCharges ELSE 0 END), 2) AS MRR_Lost
FROM customers
GROUP BY SubscriptionType, ContractDuration
ORDER BY ChurnRatePct DESC;

-- C10. Churn risk profile: high-risk vs low-risk comparison
SELECT 
    CASE 
        WHEN ContractDuration = 'Month-to-Month' AND SupportTickets >= 3 THEN 'High Risk'
        WHEN ContractDuration IN ('One Year', 'Two Year') AND SupportTickets < 3 THEN 'Low Risk'
        ELSE 'Medium Risk'
    END AS RiskProfile,
    COUNT(*) AS TotalCustomers,
    SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) AS ChurnedCustomers,
    ROUND(SUM(CASE WHEN Churn = 'Yes' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS ChurnRatePct,
    ROUND(AVG(MonthlyCharges), 2) AS AvgMonthlyCharges,
    ROUND(SUM(MonthlyCharges), 2) AS TotalMRR
FROM customers
GROUP BY RiskProfile
ORDER BY ChurnRatePct DESC;
